const PAGE_MAP = {
  "/dashboard": "dashboard",
  "/program": "program",
  "/history": "program",
  "/cli": "program",
  "/profile": "profile",
  "/assessment": "empty-no-program",
};

export function getIdleKey(pathname) {
  if (PAGE_MAP[pathname]) return PAGE_MAP[pathname];
  if (pathname.startsWith("/program/day/")) return "task";
  if (pathname.startsWith("/submit/")) return "submit";
  if (pathname.startsWith("/admin")) return null;
  return "dashboard";
}
